create table if not exists public.mayor_profile (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  name_kana text,
  birth_date text,
  image_url text,
  official_url text,
  is_current boolean,
  start_date date,
  end_date date,
  term_number integer,
  bio text
);

alter table public.mayor_profile enable row level security;

alter table public.meetings
  add column if not exists mayor_proposal_text text,
  add column if not exists mayor_proposal_summary text,
  add column if not exists mayor_proposal_source_url text;

comment on column public.meetings.mayor_proposal_text is
  '市長が議会（定例会等）で述べる「提案理由説明」の本文';

comment on column public.meetings.mayor_proposal_summary is
  '市長提案理由説明の要約';

comment on column public.meetings.mayor_proposal_source_url is
  '市長提案理由説明の公式原文URL';
